# ── Data loader ───────────────────────────────────────────────
CLEAN_DIR = '../data/clean'

@st.cache_data
def load(name):
    path = f'{CLEAN_DIR}/{name}.csv'
    if not os.path.exists(path):
        st.warning(f'Missing: {path} — run notebooks 00 and 01 first.')
        return None
    df = pd.read_csv(path)
    if 'year' not in df.columns and 'date' in df.columns:
        df['date'] = pd.to_datetime(df['date'], errors='coerce')
        df['year'] = df['date'].dt.year
    return df

pop_malaysia        = load('population_malaysia')
pop_state           = load('population_state')
fertility           = load('fertility')
fertility_state     = load('fertility_state')
births              = load('births_annual')
