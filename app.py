    c2.metric("👶 Fertility Rate (TFR)", f"{tfr_row['fertility_rate']:.2f}",    "⚠️ Below 2.1" if tfr_row['fertility_rate'] < 2.1 else "✅ Above 2.1")
    c3.metric("📉 Ageing Index",         f"{ai:.1f}",                            "⚠️ Ageing Nation" if ai >= 100 else "Approaching 100")
    c4.metric("📅 TFR Data Year",        str(int(tfr_row['year'])),             "Latest available")

    st.markdown("---")
